/**
 * Reads the SQL migrations `drizzle-kit generate` writes and renders them as the TypeScript module `src/storage/migrations.ts`, so a browser build needs no file access to apply them. `embed-migrations.ts` writes the module; a test compares it to this rendering so the two cannot drift.
 */

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

/** The text drizzle-kit puts between the statements of one migration file. */
const BREAKPOINT = "--> statement-breakpoint";

/** One migration: its folder name and the statements of its SQL file. */
export interface MigrationFile {
  readonly tag: string;
  readonly statements: readonly string[];
}

/** The migrations in `directory`, in the order drizzle-kit generated them (folder names begin with a timestamp). */
export function readMigrationFiles(directory: string): MigrationFile[] {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((tag) => ({
      tag,
      statements: readFileSync(join(directory, tag, "migration.sql"), "utf8")
        .split(BREAKPOINT)
        .map((statement) => statement.trim())
        .filter((statement) => statement !== ""),
    }));
}

/** The source of `src/storage/migrations.ts` for these migrations. */
export function renderMigrationsModule(migrations: readonly MigrationFile[]): string {
  const entries = migrations
    .map(
      (migration) =>
        `  {\n    tag: ${JSON.stringify(migration.tag)},\n    statements: [\n${migration.statements
          .map((statement) => `      ${JSON.stringify(statement)},\n`)
          .join("")}    ],\n  },\n`,
    )
    .join("");
  return `// Generated by scripts/embed-migrations.ts from src/storage/migrations/. Do not edit by hand.

/** One SQL migration: its folder name and its statements, in order. */
export interface Migration {
  readonly tag: string;
  readonly statements: readonly string[];
}

/** Every migration \`drizzle-kit generate\` has produced for \`schema.ts\`, oldest first. */
export const MIGRATIONS: readonly Migration[] = [\n${entries}];
`;
}
