class FrozenDatetime(datetime):
    """`datetime` whose clock stands still, so timestamps in output are reproducible."""

    @classmethod
    def now(cls, tz: Any = None) -> datetime:  # type: ignore[override]
        return FROZEN


class StoppedLoop:
    """The part of an event loop the sampling commands use to time themselves, never advancing."""

    def time(self) -> float:
        return 0.0


STOPPED_ASYNCIO = types.SimpleNamespace(
    get_running_loop=StoppedLoop, sleep=asyncio.sleep, CancelledError=asyncio.CancelledError
)


def bytes_of(text: str) -> bytes:
    return bytes.fromhex(text)


def table_responder(table: Json) -> Callable[[bytes], list[tuple[int, bytes]]]:
    """A functional-address responder: request hexadecimal to [[sender, reply hexadecimal]]."""

    def respond(request: bytes) -> list[tuple[int, bytes]]:
        return [
            (int(sender, 16), bytes_of(reply))
            for sender, reply in table.get(request.hex().upper(), [])
        ]

    return respond


def unit_responder(spec: Json) -> Callable[[bytes], list[tuple[int, bytes]]]:
    """A scripted unit, with the extras a scenario asks for around the stock behaviour."""
    faults = [(int(code, 16), int(status, 16)) for code, status in spec.get("faults", [])]
    response = int(spec["response"], 16)
    unit: KwpEcu | UdsEcu
    unit = UdsEcu(response, faults) if spec["protocol"] == "uds" else KwpEcu(response, faults)
    unit.writes_refused = spec.get("writesRefused", False)
    if isinstance(unit, KwpEcu):
        unit.freeze_refused = spec.get("freezeRefused", False)
    for key, value in spec.get("records", {}).items():
        unit.records[int(key, 16)] = bytes_of(value)
    values = {int(key, 16): bytes_of(value) for key, value in spec.get("values", {}).items()}
    refuse_all = spec.get("refuseAll", False)

    def respond(request: bytes) -> list[tuple[int, bytes]]:
        if refuse_all:
            return [(response, bytes([0x7F, request[0], 0x11]))]
        if values and request[0] == 0x21 and len(request) == 2:
            data = values.get(request[1])
            if data is None:
                return [(response, bytes([0x7F, 0x21, 0x31]))]
            return [(response, bytes([0x61, request[1]]) + data)]
        if values and request[0] == 0x22 and len(request) == 3:
            data = values.get(int.from_bytes(request[1:3], "big"))
            if data is None:
                return [(response, bytes([0x7F, 0x22, 0x31]))]
            return [(response, bytes([0x62]) + request[1:3] + data)]
        return unit(request)

    return respond


class SilentTransport:
    """An adapter that never says anything."""

    async def open(self) -> None: ...

    async def close(self) -> None: ...

    async def write(self, data: bytes) -> None: ...

    async def read(self, timeout: float) -> bytes:
        from obd_read.transport import TransportTimeout

        raise TransportTimeout("the silent adapter says nothing")


class RefusingTransport(SilentTransport):
    """An adapter whose link cannot be opened."""

    def __init__(self, message: str) -> None:
        self.message = message

    async def open(self) -> None:
        raise TransportError(self.message)


def make_transport(car: Json, profiles: dict[str, str]) -> Transport:
    kind = car["kind"]
    if kind == "silent":
        return SilentTransport()  # type: ignore[return-value]
    if kind == "refusing":
        return RefusingTransport(car["message"])  # type: ignore[return-value]
    if kind == "simulated":
        return FakeTransport(simulated_car(load_profile(car["profile"])))
    if kind == "elm":
        responders: dict[int, Any] = {}
        for spec in car.get("units", []):
            responders[int(spec["request"], 16)] = unit_responder(spec)
        if "functional" in car:
            responders[0x7DF] = table_responder(car["functional"])
        core = FakeElmCore(
            responders,
            unsupported=frozenset(car.get("unsupported", [])),
            stn_identity=car.get("stn"),
        )
        return FakeTransport(core)
    if kind == "kline":
        tables: dict[int, Json] = {int(key, 16): value for key, value in car["units"].items()}

        def unit(table: Json) -> Callable[[bytes], bytes | None]:
            def respond(request: bytes) -> bytes | None:
                reply = table.get(request.hex().upper())
                return bytes_of(reply) if reply is not None else bytes([0x7F, request[0], 0x11])

            return respond

        core_k = FakeKLineCore(
            {key: unit(table) for key, table in tables.items()},
            frozenset(int(key, 16) for key in car.get("silentInit", [])),
        )
        core_k.corrupt = car.get("corrupt", False)
        return FakeTransport(core_k)  # type: ignore[arg-type]
    if kind == "monitor":
        return MonitoringAdapter(car["stream"], stn=car.get("stn", False))  # type: ignore[return-value]
    if kind == "adapters":
        return SilentTransport()  # type: ignore[return-value]
    if kind == "rawcan":
        link = FakeCanLink({})
        for can_id, data in car["inject"]:
            link.inject(int(can_id, 16), bytes_of(data))
        return RawCanTransport(link)
    raise SystemExit(f"unknown car kind {kind}")


@contextlib.contextmanager
def scripted_radio(car: Json) -> Any:
    """Replace the Bluetooth radio and the serial port list for every scenario.

    A scenario that lists adapters gets the scripted devices of its car; any other scenario that
    reached for the radio or a port would fail loudly. Nothing here touches hardware.
    """
    import bleak
    from serial.tools import list_ports

    from obd_read.transport import ble

    scripted = car["kind"] == "adapters"

    class Advert:
        def __init__(self, spec: Json) -> None:
            self.local_name = spec["name"]
            self.rssi = spec["rssi"]

    class Device:
        def __init__(self, spec: Json) -> None:
            self.name = spec["name"]
            self.address = spec["address"]

    found = (
        {spec["address"]: (Device(spec), Advert(spec)) for spec in car["ble"]} if scripted else {}
    )

    async def discover(timeout: float = 5.0, return_adv: bool = False, **_: Any) -> Any:
        if not scripted:
            raise AssertionError("a scenario reached for the Bluetooth radio")
        return found

    async def find_device(name: str, timeout: float) -> Device:
        for device, _ in found.values():
            if device.name and name.lower() in device.name.lower():
                return device
        raise TransportError(f"no Bluetooth LE device matching {name!r} seen in {timeout:.0f} s")

    class Client:
        def __init__(self, device: Device) -> None:
            if not scripted:
                raise AssertionError("a scenario reached for the Bluetooth radio")
            self.device = device

        async def __aenter__(self) -> Client:
            return self

        async def __aexit__(self, *_: Any) -> None: ...

    def describe(_client: Any) -> list[Any]:
        return [
            types.SimpleNamespace(
                service=spec["service"], uuid=spec["uuid"], properties=spec["properties"]
            )
            for spec in car.get("services", [])
        ]

    ports = [
        types.SimpleNamespace(device=spec["device"], description=spec["description"])
        for spec in car.get("ports", [])
    ]
    saved = (bleak.BleakScanner.discover, bleak.BleakClient, ble.find_device, ble.describe_services)
    saved_ports = list_ports.comports
    bleak.BleakScanner.discover = discover  # type: ignore[assignment,method-assign]
    bleak.BleakClient = Client  # type: ignore[assignment,misc]
    ble.find_device = find_device  # type: ignore[assignment]
    ble.describe_services = describe  # type: ignore[assignment]
    list_ports.comports = lambda: ports  # type: ignore[assignment]
    try:
        yield
    finally:
        bleak.BleakScanner.discover, bleak.BleakClient = saved[0], saved[1]  # type: ignore[method-assign,misc]
        ble.find_device, ble.describe_services = saved[2], saved[3]
        list_ports.comports = saved_ports


def broker_record(broker: FakeBroker) -> Json:
    settings = broker.settings
    if settings is None:
        return {"connected": False}
    return {
        "connected": True,
        "host": settings.host,
        "port": settings.port,
        "clientId": settings.client_id,
        "tls": settings.tls,
        "will": [settings.will.topic, settings.will.payload, settings.will.retain],
        "username": settings.username,
        "password": settings.password,
        "messages": [[m.topic, m.payload, m.retain] for m in broker.messages],
        "closed": broker.closed,
    }


def resolve_argv(argv: list[str]) -> list[str]:
    """Replace `@profile:<name>` with the file the Python tool reads: TOML."""
    return [
        f"{word[len('@profile:') :]}.toml" if word.startswith("@profile:") else word
        for word in argv
    ]


def toml_literal(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise TypeError(f"no TOML form for {value!r}")


def toml_text(data: Json, path: tuple[str, ...] = ()) -> str:
    """TOML for a profile written as JSON: scalars first, then each table."""
    lines = [
        f"{key} = {toml_literal(value)}"
        for key, value in data.items()
        if not isinstance(value, dict)
    ]
    out = "\n".join(lines) + "\n" if lines else ""
    for key, value in data.items():
        if isinstance(value, dict):
            name = ".".join((*path, key))
            out += f"\n[{name}]\n" + toml_text(value, (*path, key))
    return out


async def run_scenario(scenario: Json, cars: Json, profile_sources: Json) -> Json:
    car = cars[scenario["car"]]
    stdout = io.StringIO()
    stderr = io.StringIO()
    lines: list[str] = []
    broker = FakeBroker(fail_after=scenario.get("brokerFailAfter"))
    with tempfile.TemporaryDirectory(prefix="golden-") as directory:
        work = Path(directory)
        initial: dict[str, str] = {}
        for name in scenario.get("profiles", []):
            (work / f"{name}.toml").write_text(toml_text(profile_sources[name]), encoding="utf-8")
            initial[f"{name}.toml"] = (work / f"{name}.toml").read_text(encoding="utf-8")
        for name, text in scenario.get("files", {}).items():
            (work / name).write_text(text, encoding="utf-8")
            initial[name] = text
        for name, text in scenario.get("binaryFiles", {}).items():
            (work / name).write_bytes(bytes_of(text))
            initial[name] = text
        transport = make_transport(car, {})
        answers = iter(scenario.get("answers", [scenario.get("answer", "")]))
        env_before = {key: os.environ.get(key) for key in (USER_VARIABLE, PASSWORD_VARIABLE)}
        for key in env_before:
            os.environ.pop(key, None)
        os.environ.update(scenario.get("env", {}))
        cwd = Path.cwd()
        os.chdir(work)
        status: int
        try:
            with (
                contextlib.redirect_stdout(stdout),
                contextlib.redirect_stderr(stderr),
                scripted_radio(car),
            ):
                try:
                    stop_after = scenario.get("stopAfterLines")
                    argv = resolve_argv(scenario["argv"])

                    def out(line: str) -> None:
                        lines.append(line)

                    if stop_after is None:
                        status = await run(
                            argv,
                            out,
                            lambda _prompt: next(answers, ""),
                            lambda _url: transport,
                            broker.connect,
                        )
                    else:
                        status = await run_until(argv, out, stop_after)
                except SystemExit as exit_:
                    status = exit_.code if isinstance(exit_.code, int) else 1
        finally:
            os.chdir(cwd)
            for key, value in env_before.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value
        files: dict[str, str] = {}
        for path in sorted(work.rglob("*")):
            if path.is_file():
                relative = path.relative_to(work).as_posix()
                text = path.read_bytes().decode("utf-8")
                if initial.get(relative) != text:
                    files[relative] = text
    record: Json = {
        "name": scenario["name"],
        "exit": status,
        "stdout": "".join(f"{line}\n" for line in lines) + stdout.getvalue(),
        "stderr": stderr.getvalue(),
        "files": files,
    }
    if scenario["argv"][:1] == ["mqtt"]:
        record["broker"] = broker_record(broker)
    return record


async def run_until(argv: list[str], out: Callable[[str], None], stop_after: int) -> int:
    """Run `simulate` until it has printed `stop_after` lines, then interrupt it as Ctrl-C does."""
    from obd_read.cli import build_parser

    args = build_parser().parse_args(argv)
    seen: list[str] = []

    def collect(line: str) -> None:
        seen.append(line)
        out(line)

    task = asyncio.ensure_future(simulate_command(args, collect))
    while len(seen) < stop_after and not task.done():
        await asyncio.sleep(0.01)
    if task.done():
        return task.result()
    task.cancel()
    try:
        await task
    except asyncio.CancelledError:
        return 130
    return 0


def source_hash(files: list[Path]) -> str:
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def sources() -> list[Path]:
    """Everything a golden file derives from."""
    found = sorted((ROOT / "src" / "obd_read").rglob("*.py"))
    found += sorted((ROOT / "src" / "obd_read" / "profiles").glob("*.toml"))
    found += sorted((ROOT / "src" / "obd_read" / "data").glob("*"))
    found += sorted((ROOT / "tests").glob("fake_*.py"))
    found += [ROOT / "tests" / "test_monitor.py", ROOT / "tests" / "test_mqtt.py"]
    found += [ROOT / "tests" / "test_live.py", ROOT / "tests" / "transcripts.py"]
    found += [SCENARIOS, Path(__file__).resolve(), ROOT / "uv.lock"]
    return [path for path in found if path.is_file()]


async def record_all() -> dict[str, Json]:
    for module in (elm, battery, discovery, live, monitor, obd_clear, operations, writes):
        module.datetime = FrozenDatetime  # type: ignore[attr-defined]
    live.asyncio = STOPPED_ASYNCIO  # type: ignore[assignment]
    battery.asyncio = STOPPED_ASYNCIO  # type: ignore[assignment]
    data = json.loads(SCENARIOS.read_text(encoding="utf-8"))
    records: dict[str, Json] = {}
    for scenario in data["scenarios"]:
        print(scenario["name"], file=sys.stderr, flush=True)
        try:
            records[scenario["name"]] = await asyncio.wait_for(
                run_scenario(scenario, data["cars"], data["profiles"]), timeout=20
            )
        except TimeoutError:
            raise SystemExit(f"scenario {scenario['name']} did not finish in 20 s") from None
    return records


def golden_text(record: Json) -> str:
    return json.dumps(record, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the golden files are stale relative to the Python sources",
    )
    args = parser.parse_args()
    digest = source_hash(sources())
    if args.check:
        try:
            recorded = json.loads(MANIFEST.read_text(encoding="utf-8"))["sourceHash"]
        except (OSError, KeyError, json.JSONDecodeError):
            recorded = None
        if recorded != digest:
            print(
                "the golden files are stale: run `uv run --python 3.13 python -I "
                "scripts/record_golden.py` and commit ts/test/golden",
                file=sys.stderr,
            )
            return 1
        print("golden files match the Python sources")
        return 0
    if sys.version_info[:2] != PYTHON_MINOR:
        print(
            f"record with Python {PYTHON_MINOR[0]}.{PYTHON_MINOR[1]}: argparse messages differ between versions",
            file=sys.stderr,
        )
        return 1
    records = asyncio.run(record_all())
    for stale in GOLDEN.glob("*.golden.json"):
        stale.unlink()
    for name, record in records.items():
        (GOLDEN / f"{name}.golden.json").write_text(golden_text(record), encoding="utf-8")
    MANIFEST.write_text(
        json.dumps({"sourceHash": digest, "scenarios": len(records)}, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"recorded {len(records)} scenarios")
    return 0


if __name__ == "__main__":
    sys.exit(main())
