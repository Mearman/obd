"""Record what the Python command line prints, so the TypeScript command line can be held to it.

Run it with `uv run --python 3.13 python -I scripts/record_golden.py`. It drives `obd_read.cli.run` against scripted adapters (never hardware) for every scenario in `ts/test/golden/scenarios.json` and writes one `ts/test/golden/<scenario>.json` with the exact standard output, standard error, exit status and every file the command wrote. `manifest.json` records a hash of everything the golden files derive from.

`--check` writes nothing: it exits with status 1 when the golden files do not match the Python sources, the scenarios or this script, so a change to the Python tool cannot leave stale goldens behind. The goldens are only ever regenerated by this script. Delete this script, the goldens and the parity suite together with the Python package.

All times are frozen and all identifiers are invented: no real vehicle identification number is used. The TypeScript side reads the same scenarios (`ts/test/parity/`) and builds the same cars.
"""

